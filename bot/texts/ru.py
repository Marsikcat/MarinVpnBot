def human_bytes(value: int) -> str:
    if value <= 0:
        return "0 ГБ"
    gb = value / 1024 ** 3
    if gb >= 1:
        return f"{gb:.1f} ГБ".replace(".0 ", " ")
    mb = value / 1024 ** 2
    return f"{mb:.0f} МБ"


def plural_days(days: int) -> str:
    if 11 <= days % 100 <= 14:
        return f"{days} дней"
    tail = days % 10
    if tail == 1:
        return f"{days} день"
    if tail in (2, 3, 4):
        return f"{days} дня"
    return f"{days} дней"


