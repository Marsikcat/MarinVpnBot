def subscription_status_line(expires_at: Optional[datetime], active: bool) -> str:
    if not expires_at:
        return "нет"
    if active:
        return f"активна до {expires_at:%d.%m.%Y}"
    return f"истекла {expires_at:%d.%m.%Y}"


def trial_hint() -> str:
    if not runtime.trial_enabled:
        return ""
    return TRIAL_HINT.format(days=plural_days(runtime.trial_days))
